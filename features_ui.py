"""
Streamlit sections for the two additional RescueLens features:

  render_agent_corner(selected)      - AI Emergency Response Agent, as a floating
                                       button + panel in the bottom-right corner
                                       of the emergency report page
  render_emergency_agent(selected)   - the agent's content (used inside the panel)
  render_agent_command_center(reports) - the same agent, placed directly in the
                                       main Command Center (pick an incident, run)
  render_nearby_services(selected)   - Nearby Emergency Services & Resource Finder

Both are called from app.py inside the existing "selected emergency" panel
and use the same Streamlit building blocks as the rest of the app
(markdown headings, metrics, columns, bordered containers, buttons).
They are independent of each other and each one catches its own errors, so a
failure in either can never break the rest of the application.
"""

