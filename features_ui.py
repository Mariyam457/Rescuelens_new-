def _numbered(items):
    return "\n".join(f"{i}. {text}" for i, text in enumerate(items, start=1))


def _bulleted(items):
    return "\n".join(f"- {text}" for text in items)


def _show_assessment(result):
    a = result["assessment"]

    if result.get("error"):
        st.warning(result["error"])

    if result.get("ai_generated"):
        st.caption("Generated by Gemini from this incident's data.")
    else:
        st.caption("Basic guidance (not AI-generated).")

    st.markdown("**Emergency Assessment**")

    m1, m2, m3 = st.columns(3)
    m1.metric("Incident", a["incident_type"])
    m2.metric("Severity", a["severity"])
    m3.metric("Priority", a["priority_level"])

    if a.get("summary"):
        st.info(a["summary"])

    if a["immediate_risks"]:
        st.markdown("**Immediate Risks**")
        st.markdown(_bulleted(a["immediate_risks"]))

    st.markdown("**Immediate Actions**")
    st.markdown(_numbered(a["immediate_actions"]))

    st.markdown("**Required Resources**")
    st.markdown(_bulleted(a["required_resources"]))

    st.markdown("**Response Plan**")
    st.markdown(_numbered(a["response_plan"]))

    st.markdown("**Evacuation**")
    if a["evacuation_required"]:
        st.warning(
            "Evacuation is recommended."
            + (f" {a['evacuation_notes']}" if a.get("evacuation_notes") else "")
        )
    else:
        st.write(
            "No evacuation required based on the available information."
            + (f" {a['evacuation_notes']}" if a.get("evacuation_notes") else "")
        )

    if a["safety_precautions"]:
        st.markdown("**Safety Precautions**")
        st.markdown(_bulleted(a["safety_precautions"]))

    st.caption(
        "Decision support for trained operators. It does not replace "
        "professional judgement or local emergency protocols."
    )


def render_emergency_agent(selected, show_header=True):
    try:
        if show_header:
            st.markdown("### 🤖 AI Emergency Response Agent")
            st.caption(
                "Analyzes this incident and proposes severity, immediate actions, "
                "required resources and a response plan."
            )

        state_key = f"agent_result_{selected['id']}"

        if st.button(
            "RUN AI EMERGENCY AGENT",
            key=f"agent_btn_{selected['id']}",
        ):
            with st.spinner("AI agent is analyzing the incident..."):
                st.session_state[state_key] = analyze_emergency(selected)

        result = st.session_state.get(state_key)
        if result:
            _show_assessment(result)

    except Exception:
        st.warning(
            "The AI Emergency Response Agent is temporarily unavailable. "
            "The rest of RescueLens is not affected."
        )


