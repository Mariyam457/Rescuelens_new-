def render_agent_corner(selected):
    """
    AI Emergency Response Agent as a floating button in the bottom-right
    corner. Click it to open the agent panel, click again to close it.
    """
    try:
        open_key = "agent_panel_open"
        is_open = bool(st.session_state.get(open_key, False))

        with st.container(
            key="agent_corner_open" if is_open else "agent_corner_closed"
        ):
            if st.button(
                "✕ CLOSE AI AGENT" if is_open else "🤖 AI AGENT",
                key="agent_toggle",
            ):
                st.session_state[open_key] = not is_open
                st.rerun()

            if is_open:
                render_emergency_agent(selected)

            st.markdown(_CORNER_CSS, unsafe_allow_html=True)

    except Exception:
        st.warning(
            "The AI Emergency Response Agent is temporarily unavailable. "
            "The rest of RescueLens is not affected."
        )


_PRIORITY_ORDER = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}


def render_agent_command_center(reports):
    """
    The same AI Emergency Response Agent, placed directly in the main Command
    Center so it no longer needs the View button first. The operator picks an
    incident (the most urgent open one is preselected) and runs the agent; the
    agent itself (render_emergency_agent -> analyze_emergency) is unchanged.
    """
    try:
        with st.expander("🤖 AI EMERGENCY RESPONSE AGENT", expanded=True):
            if not reports:
                st.caption(
                    "No emergency reports yet. The AI agent becomes available "
                    "as soon as a report is submitted."
                )
                return

            # Same order as the Priority Queue: open cases first, most urgent first.
            ordered = sorted(
                reports,
                key=lambda r: (
                    r.get("status") == "Resolved",
                    _PRIORITY_ORDER.get(r.get("priority"), 4),
                    r.get("created_at") or "",
                ),
            )
            by_id = {r["id"]: r for r in ordered}
            ids = list(by_id)

            def _label(report_id):
                r = by_id[report_id]
                return (
                    f"#{r.get('display_number')} · {r.get('priority')} · "
                    f"{r.get('emergency_type')}"
                )

            # Keep the operator's choice, but never point at a report that is gone.
            if st.session_state.get("cc_agent_incident") not in by_id:
                st.session_state["cc_agent_incident"] = ids[0]

            st.caption(
                "Choose an incident, then run the agent to get severity, "
                "immediate actions, required resources and a response plan."
            )

            chosen_id = st.selectbox(
                "Incident to analyze",
                ids,
                format_func=_label,
                key="cc_agent_incident",
            )

            render_emergency_agent(by_id[chosen_id], show_header=False)

    except Exception:
        st.warning(
            "The AI Emergency Response Agent is temporarily unavailable. "
            "The rest of RescueLens is not affected."
        )


