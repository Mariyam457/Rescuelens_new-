MAX_PER_CATEGORY = 5


def _show_nearby_map(origin, services, state_id):
    m = folium.Map(location=[origin["lat"], origin["lon"]], zoom_start=13, control_scale=True)

    folium.Marker(
        [origin["lat"], origin["lon"]],
        tooltip="Incident location",
        icon=folium.Icon(color="black", icon="warning-sign"),
    ).add_to(m)

    for s in services:
        folium.Marker(
            [s["latitude"], s["longitude"]],
            tooltip=f"{_esc(s['name'])} · {s['distance_km']:.1f} km",
            popup=folium.Popup(
                f"<b>{_esc(s['name'])}</b><br>{_esc(s['type'])}<br>{s['distance_km']:.1f} km away",
                max_width=260,
            ),
            icon=folium.Icon(color=CATEGORIES[s["category"]][1]),
        ).add_to(m)

    st_folium(
        m,
        height=360,
        use_container_width=True,
        key=f"nearby_map_{state_id}",
        returned_objects=[],
    )


def _show_nearby_results(data, state_id):
    result = data["result"]
    origin = data["origin"]

    if not result["ok"]:
        st.warning(result["error"])
        return

    services = result["services"]

    st.caption(
        f"Search centre: {origin['label']} · radius {data['radius']} km · "
        "distances are straight-line from the search centre. Data: OpenStreetMap."
    )

    if not services:
        st.info(
            f"No emergency services were found within {data['radius']} km in "
            "OpenStreetMap. Try a larger radius, or contact your local "
            "emergency number directly."
        )
        return

    _show_nearby_map(origin, services, state_id)

    for key, (label, _color) in CATEGORIES.items():
        group = [s for s in services if s["category"] == key]

        st.markdown(f"**{label}** ({len(group)})")

        if not group:
            st.caption("None found in this radius.")
            continue

        for s in group[:MAX_PER_CATEGORY]:
            with st.container(border=True):
                left, right = st.columns([4, 1])

                with left:
                    st.markdown(f"**{s['name']}**")
                    st.caption(f"{s['type']} · {s['distance_km']:.1f} km away")
                    st.write(
                        f"Address: {s['address']}"
                        if s["address"]
                        else f"Location: {s['latitude']:.5f}, {s['longitude']:.5f}"
                    )
                    if s["phone"]:
                        st.write(f"Phone: {s['phone']}")
                    if s["website"]:
                        st.write(f"Website: {s['website']}")

                with right:
                    st.link_button(
                        "DIRECTIONS",
                        s["directions_url"],
                        use_container_width=True,
                    )

        if len(group) > MAX_PER_CATEGORY:
            st.caption(f"Showing the nearest {MAX_PER_CATEGORY} of {len(group)}.")


def render_nearby_services(selected):
    try:
        st.markdown("### 🗺️ Nearby Emergency Services & Resources")
        st.caption(
            "Hospitals, fire stations, police stations, rescue centers and "
            "evacuation points near the incident location."
        )

        state_key = f"nearby_result_{selected['id']}"

        # Incident location already stored with the report (GPS or manual).
        inc_lat = selected.get("latitude")
        inc_lon = selected.get("longitude")

        c1, c2 = st.columns([3, 1])

        with c1:
            manual = st.text_input(
                "Use a different location (optional)",
                key=f"nearby_manual_{selected['id']}",
                placeholder="Leave empty to use the incident location",
            )

        with c2:
            radius = st.selectbox(
                "Radius (km)",
                [2, 5, 10, 15],
                index=1,
                key=f"nearby_radius_{selected['id']}",
            )

        if st.button(
            "FIND NEARBY SERVICES",
            key=f"nearby_btn_{selected['id']}",
        ):
            origin = None

            if manual.strip():
                with st.spinner("Looking up the location..."):
                    found = geocode_location(manual)
                if found:
                    origin = {"lat": found[0], "lon": found[1], "label": found[2]}
                else:
                    st.warning(
                        "Could not find that location. Using the incident "
                        "location instead."
                    )

            if origin is None and valid_coordinates(inc_lat, inc_lon):
                origin = {
                    "lat": float(inc_lat),
                    "lon": float(inc_lon),
                    "label": selected.get("location") or f"{float(inc_lat):.5f}, {float(inc_lon):.5f}",
                }

            if origin is None:
                st.session_state[state_key] = {
                    "origin": {"lat": 0, "lon": 0, "label": ""},
                    "radius": radius,
                    "result": {
                        "ok": False,
                        "error": (
                            "This incident has no valid location, so nearby "
                            "services cannot be searched. Enter a location above."
                        ),
                        "services": [],
                    },
                }
            else:
                with st.spinner("Searching for nearby emergency services..."):
                    result = find_nearby_services(origin["lat"], origin["lon"], radius)
                st.session_state[state_key] = {
                    "origin": origin,
                    "radius": radius,
                    "result": result,
                }

        data = st.session_state.get(state_key)
        if data:
            _show_nearby_results(data, selected["id"])

    except Exception:
        st.warning(
            "Nearby emergency services are temporarily unavailable. "
            "The rest of RescueLens is not affected."
        )